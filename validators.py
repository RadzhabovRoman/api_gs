"""
Валидация полей POST /search: name (ФИО / наименование ЮЛ), inn.

Здесь — регулярки, списки ОПФ/стоп-слов, нормализация (как norm_party в Postgres)
и функции-помощники. Pydantic-модель SearchBody и её model_validator — в app.py.
"""
import re


# ---------------------------------------------------------------------------
# Регулярки для name
# ---------------------------------------------------------------------------
# ФИО (ФЛ/ИП): кириллица, пробелы, дефис. Без латиницы, цифр, пунктуации.
RE_PERSON_NAME = re.compile(r'^[А-Яа-яЁё\s\-]+$')

# Наименование ЮЛ: широкий набор — кириллица, латиница, цифры, пробелы,
# почти вся печатная пунктуация (кавычки, №, тире, многоточие и т.д.).
RE_LEGAL_NAME = re.compile(
    r"^[а-яёА-ЯЁa-zA-Z0-9\s!\"#$%&'()*+,\-./:;<=>?@[\\\]^`{|}~«»„“‘’№–—…]+$"
)


# ---------------------------------------------------------------------------
# ИНН
# ---------------------------------------------------------------------------
# ЮЛ: ровно 10 цифр. ИП/ФЛ: ровно 12 цифр.
RE_INN_LEGAL = re.compile(r'^\d{10}$')
RE_INN_IP    = re.compile(r'^\d{12}$')


def is_valid_inn(inn: str, length: int) -> bool:
    """ИНН: ровно `length` цифр и не все цифры одинаковые."""
    if length == 10:
        if not RE_INN_LEGAL.match(inn):
            return False
    elif length == 12:
        if not RE_INN_IP.match(inn):
            return False
    else:
        raise ValueError(f'unsupported inn length: {length}')
    if len(set(inn)) == 1:
        return False
    return True


# ---------------------------------------------------------------------------
# Нормализация — та же логика, что public.norm_party(text) в Postgres:
#   lower, ё->е, дефис/тире->пробел, удалить всё кроме букв/цифр/пробелов,
#   схлопнуть пробелы, trim.
# Нужна, чтобы проверки в API совпадали с тем, как ищется в БД.
# ---------------------------------------------------------------------------
def normalize_party(txt: str) -> str:
    s = (txt or '').lower().replace('ё', 'е')
    s = re.sub(r'[-—–]', ' ', s)
    s = re.sub(r'[^а-яa-z0-9\s]', '', s)
    s = re.sub(r'\s+', ' ', s)
    return s.strip()


# ---------------------------------------------------------------------------
# ОПФ (организационно-правовые формы).
# Вырезаются как ФРАЗА В НАЧАЛЕ нормализованного name, потом проверяется
# значимое слово. В списке — аббревиатуры и полные формы.
# ---------------------------------------------------------------------------
OPF_PHRASES = [
    # аббревиатуры
    'ооо', 'ао', 'пао', 'сао', 'гуп', 'муп', 'ано', 'фку', 'мку', 'снт',
    'нао', 'гку', 'оао', 'тсн', 'тсж', 'зао',
    # полные формы
    'общество с ограниченной ответственностью',
    'публичное акционерное общество',
    'непубличное акционерное общество',
    'открытое акционерное общество',
    'закрытое акционерное общество',
    'страховое акционерное общество',
    'акционерное общество',
    'государственное унитарное предприятие',
    'муниципальное унитарное предприятие',
    'автономная некоммерческая организация',
    # «казённое» и «казенное» — на случай разного написания; после
    # normalize_party ё уже стало е, поэтому в OPF_RE достаточно «казенное»,
    # но оставляем оба на всякий случай.
    'федеральное казенное учреждение',
    'федеральное казённое учреждение',
    'муниципальное казенное учреждение',
    'муниципальное казённое учреждение',
    'государственное казенное учреждение',
    'государственное казённое учреждение',
    'садоводческое некоммерческое товарищество',
    'товарищество собственников недвижимости',
    'товарищество собственников жилья',
    'банк',
]

# Регулярка вырезания ОПФ — в ЛЮБОМ месте строки (не только в начале).
# Сортировка по длине (убывание) — чтобы «общество с ограниченной
# ответственностью» сработало раньше коротких совпадений.
# \b с обеих сторон — граница слова, чтобы «АО» не съело «АОзов».
# Применяется к нормализованному name (lower, ё->е, дефис->пробел).
OPF_RE = re.compile(
    r'\b(?:'
    + '|'.join(re.escape(p) for p in sorted(OPF_PHRASES, key=len, reverse=True))
    + r')\b',
    re.IGNORECASE,
)


# ---------------------------------------------------------------------------
# Служебные слова — исключаются по СЛОВАМ (после вырезания ОПФ).
# ---------------------------------------------------------------------------
STOPWORDS = frozenset({
    'и', 'в', 'на', 'по', 'от', 'до', 'для', 'при', 'о', 'об', 'а', 'но',
    'не', 'ни', 'с', 'к', 'у', 'из', 'за', 'над', 'под', 'без', 'через', 'между',
})


def is_meaningful_word(w: str) -> bool:
    """Слово значимо: >=3 букв, не служебное, не «аааа» (>=2 разных символа)."""
    if len(w) < 3:
        return False
    if w.lower() in STOPWORDS:
        return False
    if len(set(w.lower())) < 2:
        return False
    return True


def has_meaningful_word(name: str) -> bool:
    """Нормализует, вырезает ОПФ в начале, ищет хотя бы одно значимое слово."""
    cleaned = OPF_RE.sub(' ', normalize_party(name)).strip()
    # только буквы (цифры не считаем значимыми)
    words = re.findall(r'[а-яa-z]{2,}', cleaned)
    return any(is_meaningful_word(w) for w in words)